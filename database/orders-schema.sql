CREATE TABLE IF NOT EXISTS public.pedidos (
    id_pedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_pessoa_user_id integer NOT NULL REFERENCES public.pessoas(user_id),
    data_pedido timestamptz NOT NULL DEFAULT now(),
    tipo_entrega text NOT NULL CHECK (tipo_entrega IN ('entrega', 'retirar')),
    endereco_entrega text NOT NULL DEFAULT '',
    forma_pagamento text NOT NULL CHECK (forma_pagamento IN ('pix', 'debito', 'credito')),
    total numeric(12, 2) NOT NULL CHECK (total >= 0),
    status text NOT NULL DEFAULT 'registrado'
);

CREATE TABLE IF NOT EXISTS public.itens_pedido (
    id_item_pedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_id_pedido bigint NOT NULL REFERENCES public.pedidos(id_pedido) ON DELETE CASCADE,
    fk_id_produto integer NOT NULL REFERENCES public.produtos(id_produto),
    nome_produto text NOT NULL,
    quantidade integer NOT NULL CHECK (quantidade BETWEEN 1 AND 20),
    valor_unitario numeric(12, 2) NOT NULL CHECK (valor_unitario >= 0)
);

CREATE INDEX IF NOT EXISTS ix_pedidos_pessoa_data
    ON public.pedidos (fk_pessoa_user_id, data_pedido DESC);

CREATE INDEX IF NOT EXISTS ix_itens_pedido_pedido
    ON public.itens_pedido (fk_id_pedido);
